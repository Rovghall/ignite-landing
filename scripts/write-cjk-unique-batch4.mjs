import fs from 'node:fs'
import path from 'node:path'

function write(slug, data) {
  const en = JSON.parse(fs.readFileSync(`scripts/cjk-unique/_en/${slug}.json`, 'utf8'))
  for (const loc of ['ja', 'ko', 'zh']) {
    const t = data[loc]
    const out = { slug: en.slug, title: t.title, date: en.date, description: t.description, sections: t.sections }
    fs.mkdirSync(`scripts/cjk-unique/${loc}`, { recursive: true })
    fs.writeFileSync(path.join(`scripts/cjk-unique/${loc}`, `${slug}.json`), JSON.stringify(out, null, 2) + '\n')
  }
  console.log('ok', slug)
}

