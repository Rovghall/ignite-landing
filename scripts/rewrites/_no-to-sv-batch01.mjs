function convertPost(noPost) {
  return {
    title: titleMap[noPost.title] ?? noToSv(noPost.title),
    description: noToSv(noPost.description),
    sections: noPost.sections.map((sec) => ({
      heading: sec.heading ? noToSv(sec.heading) : undefined,
      body: sec.body.map(noToSv),
    })),
  };
}

