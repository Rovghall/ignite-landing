import fs from 'node:fs'
import path from 'node:path'

function write(slug, data) {
  const en = JSON.parse(fs.readFileSync(`scripts/cjk-unique/_en/${slug}.json`, 'utf8'))
  for (const loc of ['ja', 'ko', 'zh']) {
    const t = data[loc]
    const out = {
      slug: en.slug,
      title: t.title,
      date: en.date,
      description: t.description,
      sections: t.sections,
    }
    const dir = `scripts/cjk-unique/${loc}`
    fs.mkdirSync(dir, { recursive: true })
    fs.writeFileSync(path.join(dir, `${slug}.json`), JSON.stringify(out, null, 2) + '\n')
  }
  console.log('ok', slug)
}

